/**
 * T4: generate contract-derived negative tests straight from the OpenAPI file.
 *
 * Deliberately DETERMINISTIC (no LLM in this step). The contract is
 * machine-readable, so the cases whose oracle IS the contract (type
 * violations, missing required body, bad path params) can be enumerated
 * mechanically and reproducibly. An LLM adds value elsewhere (proposing
 * behavioural cases for a human to give an oracle; see docs/T4) and is kept
 * out of the step where determinism is the point.
 *
 * Output: tests/generated/contract-negative.generated.spec.ts
 * CI re-runs this and fails if the output differs from what is committed
 * ("generated tests are stale vs the contract").
 *
 *   npm run generate:tests                 # write
 *   npm run generate:tests -- --check      # CI: fail if stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { ContractValidator } from '../../framework/contract/validator';

type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any
const ROOT = path.resolve(__dirname, '../..');
const CONTRACT = 'contract/transactions-service.v1.yaml';
const OUT_DIR = path.join(ROOT, 'tests/generated');
const OUT = path.join(OUT_DIR, 'contract-negative.generated.spec.ts');

const v = new ContractValidator(CONTRACT);
const WRONG: Record<string, unknown[]> = {
  string: [123, true, null, {}],
  integer: ['1', 1.5, true, null],
  number: ['50', true, null, []],
};
const VALID: Record<string, unknown> = { string: '12345678901', integer: 1, number: 50 };

interface Case { id: string; title: string; method: string; path: string; body?: unknown; noBody?: boolean; expected: number[]; anchor: string }
const cases: Case[] = [];
let n = 0;
const id = () => `GEN-${String(++n).padStart(3, '0')}`;

for (const { method, template, op } of v.operations()) {
  const lineAnchor = `#/paths/${template.replace(/\//g, '~1')}/${method.toLowerCase()}`;
  const errorStatuses = Object.keys(op.responses).map(Number).filter((s) => s >= 400 && s < 500 && s !== 404 && s !== 405);
  const concrete = template.replace(/\{[^}]+\}/g, '1');

  for (const p of op.parameters ?? []) {
    if (p.in === 'path' && p.type === 'integer') {
      cases.push({ id: id(), title: `${method} ${template}: path param ${p.name}="abc" violates type integer`, method, path: template.replace(`{${p.name}}`, 'abc'), expected: errorStatuses, anchor: `${lineAnchor}/parameters (${p.name})` });
    }
    if (p.in === 'body') {
      const schema = p.schema.$ref ? v.doc.definitions[p.schema.$ref.split('/').pop()] : p.schema;
      if (p.required) {
        cases.push({ id: id(), title: `${method} ${template}: body is required but absent`, method, path: concrete, noBody: true, expected: errorStatuses, anchor: `${lineAnchor}/parameters (body.required)` });
      }
      const validBody: Record<string, unknown> = {};
      for (const [k, prop] of Object.entries<Json>(schema.properties ?? {})) validBody[k] = VALID[prop.type];
      for (const [k, prop] of Object.entries<Json>(schema.properties ?? {})) {
        for (const bad of WRONG[prop.type] ?? []) {
          cases.push({
            id: id(),
            title: `${method} ${template}: ${k}=${JSON.stringify(bad)} violates type ${prop.type}`,
            method, path: concrete, body: { ...validBody, [k]: bad }, expected: errorStatuses,
            anchor: `${p.schema.$ref ?? lineAnchor}/properties/${k}/type`,
          });
        }
      }
    }
  }
}

/** Content-type always; an idempotency key on POST /transactions so the case isolates the type error (else a missing key could be the reason for rejection). */
function headersFor(c: Case): string {
  const h = [`'content-type': 'application/json'`];
  if (c.method === 'POST' && c.path === '/transactions') h.push('[caps.idempotencyHeader]: `gen-${test.info().testId}`');
  return `{ ${h.join(', ')} }`;
}

const header = `/**
 * GENERATED by tools/ai-gen/generate-from-contract.ts from ${CONTRACT}.
 * DO NOT EDIT. Regenerate with: npm run generate:tests
 * Every case here has authority=contract and asserts ONLY what the YAML makes
 * decidable: a type/required violation must be answered with a documented 4xx.
 * Known weakness (docs/T4 §3): the status alone does not prove WHY the request
 * was rejected. A server that rejects for an unrelated reason still passes.
 */
import { test, expect } from '../../framework/fixtures';
import { oracle } from '../../framework/oracle';
`;
const body = cases.map((c) => `
test(${JSON.stringify(`${c.id} ${c.title}`)}, { tag: ['@pr', '@generated', '@contract'] }, async ({ api, caps }) => {
  oracle({ authority: 'contract', asserts: ${JSON.stringify(`rejected with one of [${c.expected.join(', ')}]`)}, source: ${JSON.stringify(c.anchor)}, risks: ['R8', 'R6'] });
  const res = await api.raw({ method: ${JSON.stringify(c.method)}, path: ${JSON.stringify(c.path)}${c.noBody ? '' : `, data: ${JSON.stringify(c.body)}`}, headers: ${headersFor(c)} });
  expect(${JSON.stringify(c.expected)}).toContain(res.status);
});
`).join('');
const source = header + body;

if (process.argv.includes('--check')) {
  const stale = !fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== source;
  if (stale) { console.error('Generated tests are stale vs the contract. Run npm run generate:tests and review the diff.'); process.exit(1); }
  console.log(`Generated tests up to date (${cases.length} cases).`);
} else {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT, source);
  console.log(`Wrote ${cases.length} generated cases to ${path.relative(ROOT, OUT)}`);
}
