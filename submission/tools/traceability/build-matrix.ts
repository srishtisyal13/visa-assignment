/**
 * Builds the C4 traceability matrix FROM THE CODE, so it cannot drift from it:
 *   case -> C1 risk it retires -> defect it catches -> CI gate
 *
 * Inputs (produce them first, in this order: npm run test:fake && npm run test:mutation):
 *   reports/results.json  from a full `TARGET=fake` run (all cases execute, so all oracles are recorded)
 *   reports/mutation.json from `npm run test:mutation` (which injected defect each case actually caught)
 * If either input is missing, or results.json is from the mock or a filtered run, it refuses and writes nothing.
 *
 * Output: docs/C4-traceability-matrix.generated.md
 * Cases with no risk id fail the build: "cases that retire no risk must be justified or cut".
 */
import fs from 'node:fs';
import path from 'node:path';
import { RISKS } from '../../framework/risks';

type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any
const ROOT = path.resolve(__dirname, '../..');
const RESULTS = path.join(ROOT, 'reports/results.json');
const MUTATION = path.join(ROOT, 'reports/mutation.json');

/** Inputs are whatever the last runs left in reports/, so check them before overwriting the committed doc. */
function refuse(why: string): never {
  console.error(`matrix: ${why}\nNothing was written. Run, in this order: npm run test:fake && npm run test:mutation && npm run matrix`);
  process.exit(1);
}
if (!fs.existsSync(RESULTS)) refuse('reports/results.json not found.');
if (!fs.existsSync(MUTATION)) refuse('reports/mutation.json not found, so the "caught in mutation run" column would be empty.');
const results = JSON.parse(fs.readFileSync(RESULTS, 'utf8'));
const mutation = JSON.parse(fs.readFileSync(MUTATION, 'utf8'));
const runTarget = results.config?.metadata?.target;
if (runTarget !== 'fake') {
  refuse(`reports/results.json comes from TARGET=${runTarget ?? 'unknown'}, not a fake run. Tests skipped on the mock never record their oracle, so they would all look like they retire no risk.`);
}

const killersByCase = new Map<string, string[]>();
for (const row of mutation.rows as { fault: string; killers: string[] }[]) {
  for (const k of row.killers) {
    const id = k.split(' ')[0];
    killersByCase.set(id, [...new Set([...(killersByCase.get(id) ?? []), row.fault])]);
  }
}

interface Row { id: string; title: string; project: string; risks: Set<string>; authorities: Set<string>; gate: string; variants: number }
const rows = new Map<string, Row>();

function gateOf(tags: string[], project: string): string {
  if (project === 'unit') return 'PR (static)';
  if (tags.includes('@nightly')) return 'Nightly';
  if (project === 'incident') return 'PR (N=25) + Pre-release (N=200 x20)';
  return 'PR';
}

const walk = (s: Json, file: string) => {
  for (const sp of s.specs ?? []) {
    for (const t of sp.tests) {
      const last = t.results[t.results.length - 1];
      const id = sp.title.split(' ')[0];
      const anns: { type: string; description?: string }[] = [...(t.annotations ?? []), ...(last?.annotations ?? [])];
      const key = `${t.projectName}:${id}`;
      const r = rows.get(key) ?? { id, title: sp.title.replace(/ @\S+/g, ''), project: t.projectName, risks: new Set(), authorities: new Set(), variants: 0, gate: gateOf(sp.tags.map((x: string) => '@' + x.replace(/^@/, '')), t.projectName) };
      r.variants++;
      for (const a of anns) {
        if (!a.type.startsWith('oracle:')) continue;
        r.authorities.add(a.type.slice('oracle:'.length));
        const m = a.description?.match(/\[risks: ([^\]]*)\]/);
        m?.[1].split(',').filter(Boolean).forEach((x) => r.risks.add(x.trim()));
      }
      rows.set(key, r);
    }
  }
  for (const c of s.suites ?? []) walk(c, c.file ?? file);
};
results.suites.forEach((s: Json) => walk(s, s.file));

// A filtered run (e.g. --project=incident) would silently drop most cases from the matrix.
const REQUIRED_PROJECTS = ['contract', 'functional', 'incident', 'e2e', 'generated'];
const missingProjects = REQUIRED_PROJECTS.filter((p) => ![...rows.values()].some((r) => r.project === p));
if (missingProjects.length) refuse(`reports/results.json is a partial run (no results for: ${missingProjects.join(', ')}).`);

const list = [...rows.values()].filter((r) => r.project !== 'unit');
const orphans = list.filter((r) => r.risks.size === 0);
const lines = [
  '# C4 traceability matrix (generated)',
  '',
  '> Generated by `npm run matrix` from the oracle annotations in the code plus `reports/mutation.json`. Do not edit by hand.',
  '> "Caught in mutation run" lists the injected defects this case actually turned red. Blank means the case guards a defect the fake does not model (see C4 §3 for the hand-written defect column).',
  '',
  '| Case | Project | Authority | Risks retired | Caught in mutation run | CI gate |',
  '|---|---|---|---|---|---|',
  ...list.map((r) => `| ${r.title.replace(/\|/g, '/')}${r.variants > 1 ? ` _(+${r.variants - 1} variants)_` : ''} | ${r.project} | ${[...r.authorities].join(', ')} | ${[...r.risks].sort().join(', ')} | ${(killersByCase.get(r.id) ?? []).map((f) => '`' + f + '`').join(' ')} | ${r.gate} |`),
  '',
  '## Risk coverage',
  '',
  '| Risk | Cases |',
  '|---|---|',
  ...Object.entries(RISKS).map(([k, v]) => `| ${k}: ${v} | ${list.filter((r) => r.risks.has(k)).length} |`),
  '',
];
fs.writeFileSync(path.join(ROOT, 'docs/C4-traceability-matrix.generated.md'), lines.join('\n'));
console.log(`matrix: ${list.length} cases, ${orphans.length} without a risk`);
if (orphans.length) { console.error('Cases retiring no risk (justify or cut):\n' + orphans.map((o) => '  ' + o.title).join('\n')); process.exit(1); }
